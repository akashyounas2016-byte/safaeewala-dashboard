import { moduleForPath, canAccessModule, normalizeRolePerms, firstAllowedPath, loginIdToEmail, passwordProblem, generatePassword, nextLoginId, DEFAULT_ROLE_PERMS } from '@/lib/permissions'
const eq = (a: unknown, b: unknown, m: string) => { if (JSON.stringify(a) !== JSON.stringify(b)) { console.log('FAIL', m, JSON.stringify(a), JSON.stringify(b)); process.exitCode = 1 } else console.log('PASS ', m) }
eq(moduleForPath('/'), 'Overview', 'root = Overview')
eq(moduleForPath('/clients/abc'), 'Clients', 'profile route maps to Clients')
eq(moduleForPath('/daily-job-sheet/spreadsheet'), 'Daily Job Sheet', 'excel maps to DJS')
eq(moduleForPath('/monthly-invoices'), 'Invoices', 'monthly invoices = Invoices')
eq(moduleForPath('/unknown'), null, 'unknown route has no module')
eq(canAccessModule('admin', DEFAULT_ROLE_PERMS, 'Settings'), true, 'admin always')
eq(canAccessModule('manager', DEFAULT_ROLE_PERMS, 'Settings'), false, 'manager no settings by default')
eq(canAccessModule('employee', DEFAULT_ROLE_PERMS, 'Invoices'), false, 'employee no invoices')
eq(canAccessModule(undefined, DEFAULT_ROLE_PERMS, 'Overview'), false, 'no user no access')
const p = normalizeRolePerms({ employee: ['Attendance', 'Dispatch'], admin: ['x'] })
eq(p.employee, ['Attendance'], 'unknown stored modules dropped')
eq(firstAllowedPath('employee', p), '/attendance', 'redirect to first allowed screen')
eq(loginIdToEmail(' SW-0007 '), 'crm-sw-0007@safaeewala.com', 'login id to email')
eq(loginIdToEmail('Owner@Mail.com'), 'owner@mail.com', 'real email kept')
eq(passwordProblem('short'), 'At least 10 characters.', 'short password rejected')
eq(passwordProblem('alllowercase1'), 'Use upper case, lower case and a number.', 'weak password rejected')
eq(passwordProblem('Strong-Pass-2026'), null, 'strong password ok')
eq(Array.from({ length: 50 }, () => passwordProblem(generatePassword())).every(x => x === null), true, 'generated passwords pass policy')
eq(nextLoginId(['admin', 'SW-0002', 'sw-0010']), 'SW-0011', 'next login id')
